# Renders docs/plan/08-collectors-world-sprint-plan.md + backlog-world.csv from backlog-world.json.
# Kept separate from render.py/backlog.json on purpose: 02 §8 forbids H3 tasks in the H1 backlog
# until the pilot gate is met. When the gate is met, merge the sprints into backlog.json.
import json, csv, os
SP = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(SP, "..", "..", ".."))
data = json.load(open(os.path.join(SP, "backlog-world.json")))
meta, sprints = data["meta"], data["sprints"]
def sid(s): return f"W{s['id']:02d}"
def planned(s): return sum(t["est"] for t in s["tasks"] if not t["title"].startswith("STRETCH"))
def stretch(s): return sum(t["est"] for t in s["tasks"] if t["title"].startswith("STRETCH"))

L = []; w = L.append
w("# 08 — Collectors World (H3) — Sprint Plan & Task Backlog")
w("")
w("> Status: **PROPOSAL v1 — 2026-10-20**, companion to `07-collectors-world.md`. Generated from `tools/backlog-world.json` — edit the JSON and re-run `python3 docs/plan/tools/render-world.py`; `backlog-world.csv` is Jira-importable. Kept out of `backlog.json` / `05` until the gate below is met (02 §8 guardrail); then merge.")
w("")
w("## Gate (nothing below starts before this)")
w("")
w(f"{meta['gate']}")
w("")
w("## Cadence & capacity")
w("")
w(f"- **Cadence:** {meta['cadence']}")
w(f"- **Planned capacity:** ≈ {meta['capacity_hours']} h per sprint; sprints are planned to 15.5–18.5 h, the rest is slack. STRETCH items only when ahead.")
w(f"- **Estimates:** {meta['estimate_note']}")
w("- **Sequencing rule:** migration → `gen:types` → domain service (+ tests) → RPC/Edge → UI → Playwright, inside every sprint (D-020).")
w(f"- **Release rule (D-028):** {meta['release_rule']}")
w("")
w("## Feature keys used below (to be added to 04 in MV-W01-01)")
w("")
w("| Key | Pillar |")
w("|---|---|")
for k, v in meta["features"].items(): w(f"| {k} | {v} |")
w("")
w("## Definition of Done (every task)")
w("")
for d in meta["definition_of_done"]: w(f"- {d}")
w("")
w("## Timeline at a glance")
w("")
w("| Sprint | Phase / theme | Planned h | Stretch h | Migration | Flag changes |")
w("|---|---|---|---|---|---|")
tp = ts = 0
for s in sprints:
    p, st = planned(s), stretch(s); tp += p; ts += st
    w(f"| {sid(s)} | {s['name']} | {p:g} | {st:g} | {s['migrations']} | {s['flags']} |")
w(f"| **Total** | 12 sprints ≈ 12 weeks build | **{tp:g}** | {ts:g} | | |")
w("")
w("First user-visible value is W03 (founders can visit each other's garages). W03 is the explicit stop/continue checkpoint.")
w("")
w("## What is live after each sprint (D-028)")
w("")
w("| Sprint | Production increment |")
w("|---|---|")
for s in sprints: w(f"| {sid(s)} | {s['ships']} |")
w("")
w("## Dependency spine")
w("")
w("W01 schema + RPCs + 18+ gate → W02 garage scene/editor/shop → W03 visits/social (flags ON founders) → W04 earn engine/quests → W05 shop complete/season/dashboard (earn ON) → W06 virtual meetups → W07 best-in-show/clubs (meetups ON) → W08 racing core → W09 race events/prizes (races ON) → W10 in-person meetups (IRL ON, UAE first) → W11 leaderboards/live-ops → W12 hardening + cohort launch. W07's clubs and W10 can swap; W08–W09 cannot move before W05 (tunes/prizes need the shop and earn engine).")
w("")
w("---")
w("")
for s in sprints:
    w(f"## Sprint {sid(s)} — {s['name']}")
    w("")
    w(f"**Goal.** {s['goal']}")
    w("")
    w(f"**Demo at end of sprint.** {s['demo']}")
    w("")
    w(f"**Ships to production.** {s['ships']}")
    w("")
    w(f"**Risks / watch-outs.** {s['risks']}")
    if s.get("decisions_locked"):
        w("")
        w("**Decisions locked this sprint:** " + "; ".join(s["decisions_locked"]))
    w("")
    w(f"**Planned hours:** {planned(s):g}" + (f" (+{stretch(s):g} stretch)" if stretch(s) else ""))
    w("")
    w("| ID | Feature | Type | Task | What done looks like | Est (h) | Depends on |")
    w("|---|---|---|---|---|---|---|")
    for t in s["tasks"]:
        w(f"| {t['id']} | {t['feature']} | {t['type']} | {t['title']} | {t['desc']} | {t['est']:g} | {t['deps'] or '—'} |")
    w("")
    w("---")
    w("")
open(os.path.join(OUT, "docs/plan/08-collectors-world-sprint-plan.md"), "w").write("\n".join(L))
with open(os.path.join(OUT, "docs/plan/backlog-world.csv"), "w", newline="") as f:
    cw = csv.writer(f)
    cw.writerow(["Issue Type","Summary","Description","Epic","Sprint","Estimate (h)","Labels","Depends On","Issue Key"])
    for s in sprints:
        for t in s["tasks"]:
            cw.writerow(["Task", f"[{t['id']}] {t['title']}", t["desc"], t["feature"], f"Sprint {sid(s)}", t["est"], t["type"] + (",stretch" if t["title"].startswith("STRETCH") else ""), t["deps"], t["id"]])
print("ok", tp, ts, sum(len(s["tasks"]) for s in sprints))
